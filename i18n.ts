class I18nManager {
  private currentLang: SupportedLang;

  constructor() {
    this.currentLang = this.detectBrowserLanguage();
  }

  /**
   * Rileva la lingua del browser dell'utente alla visita della pagina.
   * Supporta it, en, es, de, fr, zh, ru (con fallback su 'it').
   */
  public detectBrowserLanguage(): SupportedLang {
    const supportedCodes: SupportedLang[] = ['it', 'en', 'es', 'de', 'fr', 'zh', 'ru'];
    if (typeof navigator !== 'undefined') {
      const candidates =
        navigator.languages && navigator.languages.length > 0
          ? navigator.languages
          : [navigator.language || 'it'];

      for (const raw of candidates) {
        if (!raw) continue;
        const primary = raw.toLowerCase().split(/[-_]/)[0] as SupportedLang;
        if (supportedCodes.includes(primary)) {
          return primary;
        }
      }
    }
    return 'it';
  }

  public getLang(): SupportedLang {
    return this.currentLang;
  }

  public setLang(lang: SupportedLang): void {
    const supportedCodes: SupportedLang[] = ['it', 'en', 'es', 'de', 'fr', 'zh', 'ru'];
    if (supportedCodes.includes(lang)) {
      this.currentLang = lang;
    }
  }

  public getLocaleTag(): string {
    const localeMap: Record<SupportedLang, string> = {
      it: 'it-IT',
      en: 'en-US',
      es: 'es-ES',
      de: 'de-DE',
      fr: 'fr-FR',
      zh: 'zh-CN',
      ru: 'ru-RU'
    };
    return localeMap[this.currentLang] || 'it-IT';
  }

  public t(key: string, params?: Record<string, string | number>): string {
    const dict = TRANSLATIONS[this.currentLang] || TRANSLATIONS.it;
    let str = dict[key] ?? TRANSLATIONS.it[key] ?? key;
    if (params) {
      for (const [k, v] of Object.entries(params)) {
        str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
      }
    }
    return str;
  }

  /**
   * Traduce tutti gli elementi statici del DOM marcati con data-i18n, data-i18n-html, data-i18n-placeholder
   */
  public applyStaticTranslations(): void {
    if (typeof document === 'undefined') return;

    document.documentElement.lang = this.currentLang;
    document.title = this.t('page.title');

    document.querySelectorAll('[data-i18n]').forEach((el) => {
      const key = el.getAttribute('data-i18n');
      if (key) {
        el.textContent = this.t(key);
      }
    });

    document.querySelectorAll('[data-i18n-html]').forEach((el) => {
      const key = el.getAttribute('data-i18n-html');
      if (key) {
        el.innerHTML = this.t(key);
      }
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
      const key = el.getAttribute('data-i18n-placeholder');
      if (key && (el instanceof HTMLInputElement || el instanceof HTMLTextAreaElement)) {
        el.placeholder = this.t(key);
      }
    });
  }
}

const I18N = new I18nManager();
